// Helper to get bus operator by service number
export function getServiceOperator(serviceNo: string): BusOperator {
  const found = POPULAR_BUS_ROUTES.find(r => r.serviceNo === serviceNo);
  if (found) return found.operator;
  // Default realistic mapping
  const num = parseInt(serviceNo, 10);
  if (isNaN(num)) return 'SBST';
  if (num >= 900 || [67, 169, 172, 178, 188, 190, 851, 856, 960, 961, 962].includes(num)) {
    return 'SMRT';
  }
  if ([41, 49, 66, 77, 97, 98, 106, 143, 173, 177, 183, 189, 282, 284, 285, 333, 334, 335, 941, 945, 947].includes(num)) {
    return 'TTS';
  }
  if ([2, 12, 15, 34, 36, 43, 62, 82, 83, 84, 85, 118, 119, 136, 381, 382, 386].includes(num)) {
    return 'GAS';
  }
  return 'SBST';
}

